/* ==========================================================================
   DOM
   ========================================================================== */

const loader =

    document.getElementById(

        "pageLoader"

    );

/* ==========================================================================
   STATE
   ========================================================================== */

let loadingCount = 0;

/* ==========================================================================
   SHOW
   ========================================================================== */

export function showLoader(){

    if(!loader){

        return;

    }

    loadingCount++;

    loader.classList.remove(

        "hidden"

    );

}

/* ==========================================================================
   HIDE
   ========================================================================== */

export function hideLoader(){

    if(!loader){

        return;

    }

    loadingCount =

        Math.max(

            0,

            loadingCount - 1

        );

    if(

        loadingCount === 0

    ){

        loader.classList.add(

            "hidden"

        );

    }

}

/* ==========================================================================
   FORCE SHOW
   ========================================================================== */

export function forceShowLoader(){

    if(!loader){

        return;

    }

    loadingCount = 1;

    loader.classList.remove(

        "hidden"

    );

}

/* ==========================================================================
   FORCE HIDE
   ========================================================================== */

export function forceHideLoader(){

    if(!loader){

        return;

    }

    loadingCount = 0;

    loader.classList.add(

        "hidden"

    );

}

/* ==========================================================================
   RESET
   ========================================================================== */

export function resetLoader(){

    loadingCount = 0;

    forceHideLoader();

}

